import type { Expense } from '../../types'
import { categoryLabel } from '../../lib/categories'

const HEADER = ['date', 'description', 'category', 'amount'] as const
/** RFC 4180 line terminator. */
const LINE_END = '\r\n'
/** Characters that make spreadsheet apps treat a cell as a formula (CSV injection). */
const FORMULA_PREFIX = /^[=+\-@\t\r]/
const NEEDS_QUOTING = /[",\r\n]/

/**
 * Escapes one CSV field: fields containing commas, quotes or newlines are wrapped in
 * double quotes (with inner quotes doubled). Values that would be interpreted as a
 * spreadsheet formula are prefixed with `'` so they open as plain text.
 */
export function escapeCsvField(value: string): string {
  return quoteCsvField(FORMULA_PREFIX.test(value) ? `'${value}` : value)
}

/** RFC 4180 quoting only, for values we generate ourselves (e.g. numbers). */
function quoteCsvField(value: string): string {
  return NEEDS_QUOTING.test(value) ? `"${value.replace(/"/g, '""')}"` : value
}

/** Formats integer cents as a plain decimal string, e.g. 1250 -> "12.50". */
export function centsToDecimal(cents: number): string {
  const sign = cents < 0 ? '-' : ''
  const abs = Math.abs(Math.trunc(cents))
  const whole = Math.floor(abs / 100)
  const fraction = String(abs % 100).padStart(2, '0')
  return `${sign}${whole}.${fraction}`
}


/** Builds a CSV document (header + one row per expense, oldest first). */
export function buildExpensesCsv(expenses: readonly Expense[]): string {
  // ISO `YYYY-MM-DD` dates sort correctly as plain strings; Array#sort is stable.
  const sorted = [...expenses].sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0))
  const rows = sorted.map(
    (e) =>
      [
        escapeCsvField(e.date),
        escapeCsvField(e.description),
        escapeCsvField(categoryLabel(e.category)),
        // Amount is generated by us: quote-only, so negative numbers stay numeric.
        quoteCsvField(centsToDecimal(e.amountCents)),
      ].join(',') + LINE_END,
  )
  return HEADER.join(',') + LINE_END + rows.join('')
}

/** `expenses-YYYY-MM-DD.csv` using the local calendar date. */
export function csvFilename(date: Date): string {
  const y = date.getFullYear()
  const m = String(date.getMonth() + 1).padStart(2, '0')
  const d = String(date.getDate()).padStart(2, '0')
  return `expenses-${y}-${m}-${d}.csv`
}
